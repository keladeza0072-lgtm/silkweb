/** Normalize text for the bitmap font: strip diacritics, unify quotes/dashes. */
export function fontSafe(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[’‘]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, '-')
    .replace(/[•·]/g, '-');
}

export function glyphFor(char: string): string[] {
  return GLYPHS[char] ?? BLANK;
}

export interface TextMetrics {
  scale: number;
  tracking: number;
}

/** Pixel width of a single-line string at the given scale/tracking. */
export function measureLine(text: string, scale: number, tracking: number): number {
  if (text.length === 0) return 0;
  const unit = GLYPH_WIDTH * scale + tracking;
  return text.length * unit - tracking;
}

/** Pixel height of N lines at the given scale and line gap. */
export function measureBlock(lineCount: number, scale: number, lineGap: number): number {
  if (lineCount <= 0) return 0;
  return lineCount * GLYPH_HEIGHT * scale + (lineCount - 1) * lineGap;
}

/**
 * Greedy word wrap. Words longer than the line are hard-split.
 * Returns lines that each fit maxWidthPx (before callers shrink scale).
 */
export function wrapText(text: string, maxWidthPx: number, scale: number, tracking: number): string[] {
  const words = fontSafe(text).split(/\s+/).filter((w) => w.length > 0);
  const lines: string[] = [];
  let current = '';
  const fits = (line: string): boolean => measureLine(line, scale, tracking) <= maxWidthPx;
  for (const word of words) {
    if (word.length > 0 && !fits(word)) {
      if (current.length > 0) {
        lines.push(current);
        current = '';
      }
      let rest = word;
      while (rest.length > 0 && !fits(rest)) {
        let cut = rest.length - 1;
        while (cut > 1 && !fits(rest.slice(0, cut))) cut -= 1;
        lines.push(rest.slice(0, cut));
        rest = rest.slice(cut);
      }
      current = rest;
      continue;
    }
    const next = current.length === 0 ? word : `${current} ${word}`;
    if (fits(next)) {
      current = next;
    } else {
      lines.push(current);
      current = word;
    }
  }
  if (current.length > 0) lines.push(current);
  return lines.length > 0 ? lines : [''];
}

/** Largest scale in [1..maxScale] whose wrapped lines fit maxWidthPx and maxLines. */
export function fitScale(
  text: string,
  maxWidthPx: number,
  maxScale: number,
  tracking: number,
  maxLines: number,
): { scale: number; lines: string[] } {
  for (let scale = maxScale; scale >= 1; scale -= 1) {
    const lines = wrapText(text, maxWidthPx, scale, tracking);
    if (lines.length <= maxLines) return { scale, lines };
  }
  const lines = wrapText(text, maxWidthPx, 1, tracking).slice(0, Math.max(1, maxLines));
  return { scale: 1, lines };
}
