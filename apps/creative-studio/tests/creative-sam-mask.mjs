import assert from 'node:assert/strict';
import sharp from 'sharp';
import {applySamProductMask} from '../dist/creativeSamMask.js';
const width=320,height=240;
const source=await sharp({create:{width,height,channels:3,background:'#175dcc'}}).png().toBuffer();
const smallMask=Buffer.alloc(80*60);
for(let y=0;y<60;y++)for(let x=0;x<80;x++)smallMask[y*80+x]=(x>=18&&x<62&&y>=12&&y<48)?255:0;
const mask=await sharp(smallMask,{raw:{width:80,height:60,channels:1}}).png().toBuffer();
const result=await applySamProductMask(source,mask);
assert.equal(result.maskResized,true);
const pixels=await sharp(result.productCutoutPng).raw().toBuffer({resolveWithObject:true});
assert.equal(pixels.info.channels,4);
assert.equal(pixels.info.width,width);
assert.equal(pixels.info.height,height);
assert.equal(pixels.data[(10*width+10)*4+3],0);
assert.equal(pixels.data[(120*width+160)*4+3],255);
const empty=await sharp({create:{width:80,height:60,channels:3,background:'#000000'}}).png().toBuffer();
await assert.rejects(applySamProductMask(source,empty),/empty|whole/);
const full=await sharp({create:{width:80,height:60,channels:3,background:'#ffffff'}}).png().toBuffer();
await assert.rejects(applySamProductMask(source,full),/empty|whole/);
console.log('PASS: SAM mask scaling, RGBA transparency, source preservation, empty/full-mask rejection.');
console.log('NOTE: This verifies mask postprocessing, NOT a live SAM 3.1 API call.');
