import assert from 'node:assert/strict';
import sharp from 'sharp';
import {projectSamBoxMask} from '../dist/creativeSam31.js';
import {buildMuseImageRequest} from '../dist/museImage.js';
const source=await sharp({create:{width:240,height:160,channels:3,background:'#2668aa'}}).png().toBuffer();
// SAM returns a small cropped mask for bbox x=80..159, y=40..119.
const raster=new Uint8Array(20*20);
raster.fill(255);
const mask={raster,cropWidth:20,cropHeight:20,box:{left:80,top:40,right:159,bottom:119}};
const result=await projectSamBoxMask(source,mask);
assert.ok(result.maskCoverage>0.15 && result.maskCoverage<0.18,'Bounding-box projected coverage');
const {data,info}=await sharp(result.cutout).raw().toBuffer({resolveWithObject:true});
assert.equal(info.channels,4);
assert.equal(data[(0*240+0)*4+3],0);
assert.equal(data[(80*240+120)*4+3],255);
assert.equal(data[(150*240+220)*4+3],0);
await assert.rejects(projectSamBoxMask(source,{...mask,box:{left:-10,top:0,right:90,bottom:99}}),/outside/);
await assert.rejects(projectSamBoxMask(source,{...mask,raster:new Uint8Array(10)}),/dimensions/);
const input={productName:'power bank',objective:'launch-product',upload:{format:'png',bytes:source},differentiator:'',price:'',currency:'',specialOffer:'',samCutoutPng:result.cutout};
const plan={id:'a',audience:'cold',headline:'Make room',body:'A closer look.',cta:'Explore',angle:'Discovery',visualPrompt:'Real-life context'};
const scene='data:image/png;base64,'+source.toString('base64');
const request=buildMuseImageRequest(plan,input,{approvedSceneDataUrl:scene});
assert.equal(request.body.images.length,3);
assert.equal(request.body.images[0].image_url,scene,'Approved scene first');
assert.ok(request.body.images[1].image_url.includes(source.toString('base64')),'Original product second');
assert.ok(request.body.images[2].image_url.includes(result.cutout.toString('base64')),'SAM cutout last');
assert.match(request.body.prompt,/LAST image/);
const noSam=buildMuseImageRequest(plan,{...input,samCutoutPng:undefined},{approvedSceneDataUrl:scene});
assert.equal(noSam.body.images.length,2,'SAM failure retains two-image flow');
console.log('PASS: cropped SAM mask projected into correct source-image bbox; three-image Muse handoff; optional fallback.');
console.log('NOTE: No live SAM inference or Muse generation was performed.');
